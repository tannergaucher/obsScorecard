// This is the code for managing the 3-putt updates from the control panel
// and rendering them to the HTML DOM.

/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////            
//						functions
/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////            

function renderPuttCounter() {
	const threePutts = document.getElementById("threePutts");

	let count = 0;
	const putts = scoreCard.players[0].putts;

	for (let i = 0; i < putts.length; i++) {
		if (putts[i] > 2) {
			count++;
		}
	}

	setCounter(threePutts, count);
}

function setScores(scores) {
    scoreCard.players = scores;

    renderPuttCounter();
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//										variable declarations
/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////			

var scoreCard = {
   players: [
     { putts: [] },
     { putts: [] }
   ],
};


/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//										broadcast channel events
/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////			

registerBroadCastHandler((event) => {

	if (event.data.scores != null) {
		setScores(event.data.scores);
	}
});

//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//							autostart stuff
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

(() => {
	const p1Putts = localStorage.getItem("p1Putts");
	if (p1Putts != null) {
		scoreCard.players[0].putts = p1Putts.split(",");
	}

	renderPuttCounter();
	hasRendered = true;
})();

